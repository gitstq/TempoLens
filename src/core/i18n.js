  /** 取文案 / translate a key with optional {var} interpolation */
  function t(lang, key, vars) {
    var dict = MESSAGES[lang] || MESSAGES.en;
    var str = dict[key];
    if (str === undefined) { str = MESSAGES.en[key]; }
    if (str === undefined) { return key; }
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        str = str.split('{' + name + '}').join(String(vars[name]));
      });
    }
    return str;
  }

  /** 解析界面语言 / resolve UI language from preference + navigator languages */
  function resolveLang(pref, navLangs) {
    if (pref && LANGS.indexOf(pref) >= 0) { return pref; }
    var list = Array.isArray(navLangs) ? navLangs : (navLangs ? [navLangs] : []);
    for (var i = 0; i < list.length; i++) {
      var tag = String(list[i] || '');
      if (/^zh[-_](TW|HK|MO|Hant)/i.test(tag)) { return 'zh-TW'; }
      if (/^zh([-_]|$)/i.test(tag)) { return 'zh-CN'; }
    }
    return 'en';
  }

  /** 遍历文档打上文案 / apply translations to a document */
  function translateDocument(doc, lang) {
    if (typeof doc === 'undefined' || !doc) { return; }
    var html = doc.documentElement;
    if (html) { html.setAttribute('lang', lang); }
    var i;
    var nodes = doc.querySelectorAll('[data-i18n]');
    for (i = 0; i < nodes.length; i++) { nodes[i].textContent = t(lang, nodes[i].getAttribute('data-i18n')); }
    nodes = doc.querySelectorAll('[data-i18n-aria]');
    for (i = 0; i < nodes.length; i++) { nodes[i].setAttribute('aria-label', t(lang, nodes[i].getAttribute('data-i18n-aria'))); }
    nodes = doc.querySelectorAll('[data-i18n-title]');
    for (i = 0; i < nodes.length; i++) { nodes[i].setAttribute('title', t(lang, nodes[i].getAttribute('data-i18n-title'))); }
    nodes = doc.querySelectorAll('[data-i18n-placeholder]');
    for (i = 0; i < nodes.length; i++) { nodes[i].setAttribute('placeholder', t(lang, nodes[i].getAttribute('data-i18n-placeholder'))); }
  }

  return {
    LANGS: LANGS,
    MESSAGES: MESSAGES,
    t: t,
    resolveLang: resolveLang,
    translateDocument: translateDocument
  };
